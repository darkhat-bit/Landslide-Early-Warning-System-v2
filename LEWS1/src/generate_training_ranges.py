"""
generate_training_ranges.py — Synchronizes training feature bounds from dataset.csv
==================================================================================
Reads data/dataset.csv and generates frontend/src/data/trainingRanges.ts
guaranteeing bit-for-bit consistency between dataset and frontend/backend bounds.
"""

from pathlib import Path
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent.parent
DATASET_PATH = BASE_DIR / "data" / "dataset.csv"
FRONTEND_FILE = BASE_DIR.parent / "frontend" / "src" / "data" / "trainingRanges.ts"

FEATURE_METADATA = {
    "elevation_m": {"unit": "m", "sourceType": "DEM", "label": "Elevation"},
    "slope_deg": {"unit": "°", "sourceType": "DEM", "label": "Slope Gradient"},
    "aspect_deg": {"unit": "°", "sourceType": "DEM", "label": "Aspect"},
    "curvature": {"unit": "100/m", "sourceType": "DEM", "label": "Curvature (Laplacian)"},
    "dist_to_road_m": {"unit": "m", "sourceType": "HandEstimated", "label": "Distance to Road"},
    "dist_to_river_m": {"unit": "m", "sourceType": "HandEstimated", "label": "Distance to River"},
    "rain_24h_mm": {"unit": "mm", "sourceType": "Scenario", "label": "24-Hour Rainfall"},
    "rain_3d_mm": {"unit": "mm", "sourceType": "Scenario", "label": "3-Day Rainfall"},
    "rain_7d_mm": {"unit": "mm", "sourceType": "Scenario", "label": "7-Day Antecedent Rain"},
    "soil_moisture_pct": {"unit": "%", "sourceType": "Scenario", "label": "Soil Moisture"},
    "ndvi": {"unit": "index", "sourceType": "Default", "label": "NDVI (Vegetation Index)"},
}

def generate_ts():
    df = pd.read_csv(DATASET_PATH)
    ranges = {}
    for col in FEATURE_METADATA:
        ranges[col] = {
            "min": round(float(df[col].min()), 4),
            "max": round(float(df[col].max()), 4),
        }

    lines = [
        "/**",
        " * Auto-generated by src/generate_training_ranges.py from data/dataset.csv.",
        " * Do NOT edit empirical min/max numbers manually.",
        " */",
        "",
        "export interface FeatureRange {",
        "  min: number;",
        "  max: number;",
        "  unit: string;",
        "  sourceType: 'DEM' | 'HandEstimated' | 'Default' | 'Scenario' | 'LiveWeather';",
        "  label: string;",
        "}",
        "",
        "export const TRAINING_FEATURE_RANGES: Record<string, FeatureRange> = {",
    ]

    for feat, meta in FEATURE_METADATA.items():
        min_v = ranges[feat]["min"]
        max_v = ranges[feat]["max"]
        lines.append(f"  {feat}: {{")
        lines.append(f"    min: {min_v},")
        lines.append(f"    max: {max_v},")
        lines.append(f"    unit: '{meta['unit']}',")
        lines.append(f"    sourceType: '{meta['sourceType']}',")
        lines.append(f"    label: '{meta['label']}',")
        lines.append("  },")

    lines.append("};")
    lines.append("")

    # Append standard helper functions
    lines.extend([
        "export function getProvenanceLabel(",
        "  sourceType: 'DEM' | 'HandEstimated' | 'Default' | 'Scenario' | 'LiveWeather',",
        "  isLiveWeather: boolean = false",
        "): string {",
        "  if (isLiveWeather && (sourceType === 'Scenario' || sourceType === 'LiveWeather')) {",
        "    return 'Live weather model';",
        "  }",
        "  switch (sourceType) {",
        "    case 'DEM':",
        "      return 'From terrain data (DEM)';",
        "    case 'HandEstimated':",
        "      return 'Approximate (hand-estimated)';",
        "    case 'Default':",
        "      return 'Default value';",
        "    case 'Scenario':",
        "      return 'Simulated scenario';",
        "    case 'LiveWeather':",
        "      return 'Live weather model';",
        "  }",
        "}",
        "",
        "export interface FeatureEvaluation {",
        "  featureName: string;",
        "  label: string;",
        "  value: number;",
        "  unit: string;",
        "  provenance: string;",
        "  withinRange: boolean;",
        "  min: number;",
        "  max: number;",
        "  tag: string;",
        "}",
        "",
        "export interface StationReliabilityEvaluation {",
        "  isWithinTrainingRange: boolean;",
        "  outOfRangeCount: number;",
        "  outOfRangeFeatures: string[];",
        "  reliabilityBadge: string;",
        "  features: FeatureEvaluation[];",
        "}",
        "",
        "export function evaluateStationReliability(",
        "  station: {",
        "    elevation_m: number;",
        "    slope_deg: number;",
        "    aspect_deg: number;",
        "    curvature: number;",
        "    dist_to_road_m: number;",
        "    dist_to_river_m: number;",
        "    rain_24h_mm: number;",
        "    rain_3d_mm: number;",
        "    rain_7d_mm: number;",
        "    soil_moisture_pct: number;",
        "    ndvi: number;",
        "  },",
        "  rainIncrement: number = 0,",
        "  isLiveWeather: boolean = false",
        "): StationReliabilityEvaluation {",
        "  const adjustedRain24 = station.rain_24h_mm + rainIncrement;",
        "  const adjustedRain3d = station.rain_3d_mm + rainIncrement * 1.2;",
        "  const adjustedRain7d = station.rain_7d_mm + rainIncrement * 1.4;",
        "  const adjustedMoisture = Math.min(98.0, station.soil_moisture_pct + rainIncrement * 0.1);",
        "",
        "  const values: Record<string, number> = {",
        "    elevation_m: station.elevation_m,",
        "    slope_deg: station.slope_deg,",
        "    aspect_deg: station.aspect_deg,",
        "    curvature: station.curvature,",
        "    dist_to_road_m: station.dist_to_road_m,",
        "    dist_to_river_m: station.dist_to_river_m,",
        "    rain_24h_mm: adjustedRain24,",
        "    rain_3d_mm: adjustedRain3d,",
        "    rain_7d_mm: adjustedRain7d,",
        "    soil_moisture_pct: adjustedMoisture,",
        "    ndvi: station.ndvi,",
        "  };",
        "",
        "  const evaluations: FeatureEvaluation[] = [];",
        "  const outOfRangeFeatures: string[] = [];",
        "",
        "  for (const [key, range] of Object.entries(TRAINING_FEATURE_RANGES)) {",
        "    const val = values[key];",
        "    const within = val >= range.min && val <= range.max;",
        "    const prov = getProvenanceLabel(range.sourceType, isLiveWeather);",
        "    const tag = within ? prov : `${prov} · Outside training range, less reliable`;",
        "",
        "    if (!within) {",
        "      outOfRangeFeatures.push(key);",
        "    }",
        "",
        "    evaluations.push({",
        "      featureName: key,",
        "      label: range.label,",
        "      value: Number(val.toFixed(2)),",
        "      unit: range.unit,",
        "      provenance: prov,",
        "      withinRange: within,",
        "      min: range.min,",
        "      max: range.max,",
        "      tag,",
        "    });",
        "  }",
        "",
        "  const isReliable = outOfRangeFeatures.length === 0;",
        "  return {",
        "    isWithinTrainingRange: isReliable,",
        "    outOfRangeCount: outOfRangeFeatures.length,",
        "    outOfRangeFeatures,",
        "    reliabilityBadge: isReliable ? 'In Range' : 'Outside Range',",
        "    features: evaluations,",
        "  };",
        "}",
        "",
        "/**",
        " * Returns true if a calculated risk score is within delta (0.03) of either tier threshold:",
        " * 0.25 (Low -> Watch) or 0.70 (Watch -> High).",
        " */",
        "export function isBorderlineScore(score: number, delta: number = 0.03): boolean {",
        "  const tol = 1e-6;",
        "  const nearYellow = Math.abs(score - 0.25) <= delta + tol;",
        "  const nearRed = Math.abs(score - 0.70) <= delta + tol;",
        "  return nearYellow || nearRed;",
        "}",
        "",
    ])

    with open(FRONTEND_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {FRONTEND_FILE} successfully from {DATASET_PATH}.")

if __name__ == "__main__":
    generate_ts()

